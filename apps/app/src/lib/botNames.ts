/** 界面语言：zh 开头按中文，其余按英文。应用当前只有中文文案，英文留作扩展。 */
export function uiLanguage(
	language: string | undefined = typeof navigator === "undefined" ? undefined : navigator.language,
): UiLanguage {
	return language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** 骰子：从对应语言的名单里随机取一个。 */
export function pickBotName(lang: UiLanguage, random: () => number = Math.random): string {
	const list = lang === "zh" ? CHINESE_BOT_NAMES : ENGLISH_BOT_NAMES;
	return list[Math.floor(random() * list.length)];
}
